const { SR, render, rms, peak, check, done } = require('./harness');
const { TapeDegradeV2DSP } = require(__dirname + '/../../nodes-v2/tape-degrade/dsp.js');
const sine = (ctx, f = 440) => { const o = ctx.createOscillator(); o.frequency.value = f; const g = ctx.createGain(); g.gain.value = 0.5; o.connect(g); o.start(0); return g; };
const noise = ctx => { const b = ctx.createBuffer(1, SR * 4, SR); const d = b.getChannelData(0); for (let i = 0; i < d.length; i++) d[i] = (Math.random()*2-1)*0.3; const s = ctx.createBufferSource(); s.buffer = b; s.start(0); return s; };
const mk = (Cls, params = {}, src = sine) => async (ctx) => { const d = new Cls(); d.init(ctx, {}); d.connect(ctx.destination); src(ctx).connect(d.input); for (const k in params) d.setParameter(k, params[k]); return d; };
const hf = a => { let s = 0; for (let i = 1; i < a.length; i++) { const x = a[i] - a[i-1]; s += x*x; } return Math.sqrt(s / a.length); };
(async () => {
  console.log('Tape Degrade v2');
  let r = await render(1, mk(TapeDegradeV2DSP));
  check('silent init even with input present', peak(r.L, 0, 1) === 0);
  r = await render(2, mk(TapeDegradeV2DSP), [[0.05, d => d.start()]]);
  const lvl = rms(r.L, 0.5, 2) / (0.5 / Math.SQRT2);
  check('passes audio after start, near unity level', lvl > 0.6 && lvl < 1.2, `gain=${lvl.toFixed(2)}`);
  r = await render(2, mk(TapeDegradeV2DSP), [[0.05, d => d.start()], [1.0, d => d.stop()]]);
  check('stop silences within 0.1 s', peak(r.L, 1.1, 2) < 1e-4, peak(r.L,1.1,2).toExponential(2));
  r = await render(3, mk(TapeDegradeV2DSP), [[0.05, d => d.start()], [1.0, d => d.stop()], [2.0, d => d.start()]]);
  check('restart works (LFOs not re-started)', rms(r.L, 2.3, 3) > 0.1, rms(r.L,2.3,3).toFixed(3));
  const w0 = await render(2, mk(TapeDegradeV2DSP, { wear: 0, noise: 0 }, noise), [[0.02, d => d.start()]]);
  const w1 = await render(2, mk(TapeDegradeV2DSP, { wear: 1, noise: 0 }, noise), [[0.02, d => d.start()]]);
  check('wear removes highs', hf(w1.L.subarray(SR)) < 0.5 * hf(w0.L.subarray(SR)), `${hf(w1.L.subarray(SR)).toFixed(3)} vs ${hf(w0.L.subarray(SR)).toFixed(3)}`);
  r = await render(2, mk(TapeDegradeV2DSP, { mix: 0, noise: 0 }), [[0.05, d => d.start()]]);
  check('mix 0 -> no wet', rms(r.L, 0.5, 2) < 1e-3, rms(r.L,0.5,2).toExponential(2));
  const d = new TapeDegradeV2DSP();
  d.setParameter('damage', 5); check('clamp', d.getParameter('damage') === 1);
  d.setParameter('foo', 1); check('unknown ignored', d.getParameter('foo') === undefined);
  check('getParameters has 6', Object.keys(d.getParameters()).length === 6);
  r = await render(2, mk(TapeDegradeV2DSP), [[0.05, d => d.start()], [0.8, d => { d.dispose(); d.dispose(); }]]);
  check('dispose twice safe + silent', peak(r.L, 0.95, 2) < 1e-4);
  done();
})().catch(e => { console.error(e); process.exit(1); });
