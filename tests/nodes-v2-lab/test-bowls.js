const { SR, render, rms, peak, check, done } = require('./harness');
const { SingingBowlsV2DSP } = require(__dirname + '/../../nodes-v2/singing-bowls/dsp.js');
const mk = (params = {}) => async (ctx) => { const d = new SingingBowlsV2DSP(); d.init(ctx, {}); d.connect(ctx.destination); for (const k in params) d.setParameter(k, params[k]); await d.ready; return d; };
const zc = (a, t0, t1) => { let c = 0; for (let i = Math.floor(t0*SR)+1; i < t1*SR; i++) if (a[i-1] <= 0 && a[i] > 0) c++; return c / (t1 - t0); };
(async () => {
  console.log('Singing Bowls v2');
  let r = await render(3, mk());
  check('silent init (never started)', peak(r.L, 0, 3) === 0);
  r = await render(6, mk({ activity: 1 }), [[0.05, d => d.start()]]);
  check('sound after start (first strike immediate)', rms(r.L, 1, 2) > 0.005, `rms 1-2s=${rms(r.L,1,2).toFixed(4)}`);
  check('keeps playing', rms(r.L, 4, 6) > 0.005, rms(r.L,4,6).toFixed(4));
  r = await render(5, mk({ activity: 1 }), [[0.05, d => d.start()], [2.5, d => d.stop()]]);
  check('stop silences within 0.2 s (no 18 s ring-out)', peak(r.L, 2.75, 5) === 0, `peak=${peak(r.L,2.75,5)}`);
  r = await render(5, mk({ activity: 1 }), [[0.05, d => d.start()], [1.5, d => d.stop()], [2.5, d => d.start()]]);
  check('resume after stop', rms(r.L, 3.5, 5) > 0.005, rms(r.L,3.5,5).toFixed(4));
  const lowTone = { tone_1: 0, tone_2: 0, tone_3: 0, tone_4: 0, tone_5: 0, activity: 1, beatingMix: 0 };
  const a = await render(6, mk({ ...lowTone, rootPitch: 100 }), [[0.05, d => d.start()]]);
  const b = await render(6, mk({ ...lowTone, rootPitch: 200 }), [[0.05, d => d.start()]]);
  const ratio = zc(b.L, 2, 6) / zc(a.L, 2, 6);
  check('rootPitch 200 vs 100 ≈ one octave up', ratio > 1.7 && ratio < 2.3, `ratio=${ratio.toFixed(2)}`);
  const d = new SingingBowlsV2DSP();
  d.setParameter('rootPitch', 1000); check('clamp', d.getParameter('rootPitch') === 300);
  d.setParameter('x', 1); check('unknown ignored', d.getParameter('x') === undefined);
  check('getParameters has all 9', Object.keys(d.getParameters()).length === 9);
  r = await render(2, mk(), [[0.05, d => d.start()], [0.8, d => { d.dispose(); d.dispose(); }]]);
  check('dispose twice safe + silent', peak(r.L, 0.9, 2) < 1e-4);
  const src = require('fs').readFileSync(__dirname + '/../../nodes-v2/singing-bowls/dsp.js', 'utf8');
  check('no raw worklet keywords', !src.includes('register' + 'Processor') && !src.includes('AudioWorklet' + 'Processor'));
  check('host class regex', (src.match(/class\s+(\w+DSP)\b/) || [])[1] === 'SingingBowlsV2DSP');
  done();
})().catch(e => { console.error(e); process.exit(1); });
